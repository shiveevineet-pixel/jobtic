import React, { useState } from 'react';
import { ChevronDown, ChevronUp, ArrowLeft, RotateCcw, ThumbsUp, AlertTriangle, Lightbulb, Download, CheckCircle2 } from 'lucide-react';
import { InterviewSession } from '../services/storageService';
import { Share } from '@capacitor/share';
import { Capacitor } from '@capacitor/core';
import { nativeDocumentService } from '../services/nativeDocumentService';
import { getQuestionMetrics } from '../services/studioMetrics';

interface FeedbackReportViewProps {
  session: InterviewSession;
  onBackToDashboard: () => void;
  onRetry: () => void;
}

export const FeedbackReportView: React.FC<FeedbackReportViewProps> = ({
  session,
  onBackToDashboard,
  onRetry
}) => {
  const [expandedIndex, setExpandedIndex] = useState<number | null>(0);
  const [isExporting, setIsExporting] = useState(false);
  const [downloadMsg, setDownloadMsg] = useState('');

  const getScoreTier = (score: number) => {
    if (score >= 80) return { label: 'Excellent', class: 'high' };
    if (score >= 60) return { label: 'Good', class: 'mid' };
    return { label: 'Needs Practice', class: 'low' };
  };

  const getScoreClass = (score: number) => {
    if (score >= 80) return 'score-high';
    if (score >= 60) return 'score-mid';
    return 'score-low';
  };

  const tier = getScoreTier(session.overallScore);

  const toggleExpand = (index: number) => {
    if (expandedIndex === index) {
      setExpandedIndex(null);
    } else {
      setExpandedIndex(index);
    }
  };

  const metrics = getQuestionMetrics(session.questions);
  const avgTechnical = metrics.technical;
  const avgCommunication = metrics.communication;
  const avgStructure = metrics.structure;

  const generateReportText = () => {
    return `JOBTIC AI INTERVIEW REPORT
Role: ${session.roleTitle} (${session.difficulty})
Overall Score: ${session.overallScore}% (${tier.label})
Technical: ${avgTechnical === null ? '—' : avgTechnical + '/100'} | Communication: ${avgCommunication === null ? '—' : avgCommunication + '/100'} | Structure: ${avgStructure === null ? '—' : avgStructure + '/100'}
Date: ${session.date}

QUESTIONS & BREAKDOWN:
${session.questions.map((q, idx) => `
-----------------------------------------
${idx + 1}. ${q.questionText}
Score: ${q.score}% | Technical: ${q.technicalScore ?? q.score}% | Clarity: ${q.communicationScore ?? q.score}% | Structure: ${q.structureScore ?? q.score}%

Your Response:
${q.userResponse || 'No response recorded.'}

Strengths:
${q.strengths || 'None recorded.'}

Areas to Improve:
${q.weaknesses || 'None recorded.'}

Coaching Feedback:
${q.feedback || 'None recorded.'}
`).join('\n')}
Generated by Jobtic AI Interviewer`;
  };

  const handlePrintPdf = () => {
    if (Capacitor.isNativePlatform()) {
      handleShareReport();
      return;
    }
    try {
      window.print();
    } catch (e) {
      console.warn('window.print failed:', e);
      handleDownloadReport();
    }
  };

  const handleShareReport = async () => {
    try {
      const text = generateReportText();
      if (Capacitor.isNativePlatform()) {
        await Share.share({
          title: `Jobtic - ${session.roleTitle} Report`,
          text: text,
          dialogTitle: 'Save / Share Interview Report'
        });
      } else if (navigator.share) {
        await navigator.share({
          title: `Jobtic - ${session.roleTitle} Report`,
          text: text
        });
      } else {
        await navigator.clipboard.writeText(text);
        setDownloadMsg('Report copied to clipboard!');
      }
    } catch (e) {
      console.log('Share canceled or closed:', e);
    }
  };

  const handleCopyReport = async () => {
    try {
      await navigator.clipboard.writeText(generateReportText());
      setDownloadMsg('Complete report copied to clipboard!');
    } catch {
      setDownloadMsg('Could not copy to clipboard.');
    }
  };

  const handleDownloadReport = () => {
    setIsExporting(true);
    setDownloadMsg('');

    // Run asynchronously to keep the UI thread responsive
    setTimeout(async () => {
      try {
        const filename = `Jobtic_${session.roleTitle.replace(/\s+/g, '_')}_Report.pdf`.replace(/[^a-zA-Z0-9._-]/g, '_');

        if (Capacitor.isNativePlatform()) {
          const result = await nativeDocumentService.saveTextPdf({
            filename,
            title: 'Jobtic - AI Interview Feedback Report',
            content: generateReportText()
          });
          setDownloadMsg(`PDF saved to ${result.location}`);
          return;
        }

        // Load the PDF engine only when exporting. Keeping it out of the main
        // bundle prevents Android WebViews from running out of memory on launch.
        const { createInterviewPdf } = await import('../services/reportPdf');
        const doc = createInterviewPdf(session);

        doc.save(filename);
        setDownloadMsg(`PDF downloaded successfully: ${filename}`);
      } catch (err) {
        console.error('PDF export error:', err);
        const message = err instanceof Error ? err.message : 'Could not save the report PDF.';
        setDownloadMsg(message);
      } finally {
        setIsExporting(false);
      }
    }, 100);
  };


  return (
    <div className="feedback-container">
      <h1>Session reflection</h1>
      {/* Back navigation */}
      <button 
        className="btn-secondary" 
        onClick={onBackToDashboard}
        style={{ padding: '8px 12px', fontSize: '14px', alignSelf: 'flex-start' }}
      >
        <ArrowLeft size={16} /> Back to history
      </button>

      {/* Header Evaluation Score */}
      <div className="feedback-header">
        <div className={`overall-score-circle ${tier.class}`}>
          <span className="overall-score-value">{session.overallScore}%</span>
          <span className="overall-score-label">{tier.label}</span>
        </div>
        <div className="feedback-meta">
          <span className="eyebrow">Your practice, reflected</span>
          <h3 className="feedback-meta-title">{session.roleTitle}</h3>
          <span className="feedback-meta-details">
            Difficulty: <span style={{ textTransform: 'capitalize' }}>{session.difficulty}</span> | Focus: <span style={{ textTransform: 'capitalize' }}>{session.type.replace('_', ' ')}</span>
          </span>
          <p>{session.questions[0]?.feedback || 'Review your answers and choose one useful improvement for your next session.'}</p>
          <p className="caption">AI coaching score for this session, not a measure of job readiness.</p>
          <button className="btn-primary feedback-retry" onClick={onRetry}><RotateCcw size={16} />Practice again</button>
        </div>
      </div>

      {/* Category Progress Rating Bars */}
      <div className="category-scores">
        <div className="category-card glass" style={{ borderBottom: '3px solid var(--primary)' }}>
          <span className="category-score">{avgTechnical === null ? '—' : avgTechnical + '/100'}</span>
          <span className="category-label">Technical</span>
        </div>
        
        <div className="category-card glass" style={{ borderBottom: '3px solid var(--secondary)' }}>
          <span className="category-score">{avgCommunication === null ? '—' : avgCommunication + '/100'}</span>
          <span className="category-label">Clarity</span>
        </div>

        <div className="category-card glass" style={{ borderBottom: '3px solid var(--success)' }}>
          <span className="category-score">{avgStructure === null ? '—' : avgStructure + '/100'}</span>
          <span className="category-label">Structure</span>
        </div>
      </div>

      <hr style={{ border: 'none', borderTop: '1px solid var(--border-dim)', margin: '4px 0' }} />

      {/* Questions List */}
      <div>
        <h4 className="section-title" style={{ fontSize: '0.95rem', marginBottom: '16px' }}>
          Question breakdown
        </h4>
        
        <div className="question-cards-container">
          {session.questions.map((q, idx) => {
            const isExpanded = expandedIndex === idx;
            return (
              <div key={q.questionId} className="q-feedback-item glass">
                {/* Header accordion block */}
                <button type="button" className="q-feedback-header" aria-expanded={isExpanded} aria-controls={'question-feedback-' + idx} onClick={() => toggleExpand(idx)}>
                  <span className="q-feedback-text">
                    {idx + 1}. {q.questionText}
                  </span>
                  <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
                    <span className={`q-feedback-score-badge ${getScoreClass(q.score)}`}>
                      {q.score}%
                    </span>
                    {isExpanded ? <ChevronUp size={16} /> : <ChevronDown size={16} />}
                  </div>
                </button>

                {/* Details Accordion Panel */}
                {isExpanded && (
                  <div className="q-feedback-details" id={'question-feedback-' + idx}>
                    <p style={{ fontSize: '14px', color: 'var(--text-secondary)', marginBottom: '8px' }}>
                      <strong>Full Question:</strong> {q.questionText}
                    </p>
                    
                    <div className="detail-section">
                      <span className="detail-title">
                        Your response
                      </span>
                      <div className="detail-body user-ans">
                        "{q.userResponse}"
                      </div>
                    </div>

                    <div className="detail-section">
                      <span className="detail-title">
                        <ThumbsUp size={12} style={{ color: 'var(--success)' }} /> Strengths
                      </span>
                      <div className="detail-body ai-feed">
                        {q.strengths || "Response provided, but details were insufficient to score strengths."}
                      </div>
                    </div>

                    <div className="detail-section">
                      <span className="detail-title">
                        <AlertTriangle size={12} style={{ color: 'var(--warning)' }} /> Improvements
                      </span>
                      <div className="detail-body ai-feed" style={{ borderLeftColor: 'var(--warning)' }}>
                        {q.weaknesses || "No critical improvement items identified."}
                      </div>
                    </div>

                    <div className="detail-section">
                      <span className="detail-title">
                        <Lightbulb size={12} style={{ color: 'var(--secondary)' }} /> Suggested Answer
                      </span>
                      <div className="detail-body model-ans">
                        {q.modelAnswer}
                      </div>
                    </div>

                    {q.feedback && (
                      <div className="detail-section">
                        <span className="detail-title">Coaching feedback</span>
                        <p style={{ fontSize: '14px', color: 'var(--text-secondary)', lineHeight: '1.4' }}>
                          {q.feedback}
                        </p>
                      </div>
                    )}
                  </div>
                )}
              </div>
            );
          })}
        </div>
      </div>

      {downloadMsg && (
        <div className="notice" role="status">
          <CheckCircle2 size={16} />
          <span style={{ flex: 1 }}>{downloadMsg}</span>
          <button className="icon-btn" aria-label="Dismiss export message" onClick={() => setDownloadMsg('')}>×</button>
        </div>
      )}

      {/* Footer controls */}
      <div className="feedback-footer" style={{ display: 'flex', flexDirection: 'column', gap: '8px' }}>
        <button
          className="btn-primary"
          onClick={handleDownloadReport}
          disabled={isExporting}
          style={{ justifyContent: 'center', width: '100%' }}
        >
          <Download size={16} /> {isExporting ? 'Generating PDF...' : 'Download PDF Report'}
        </button>
        <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '8px', width: '100%' }}>
          <button className="btn-secondary" onClick={handlePrintPdf} style={{ justifyContent: 'center', fontSize: '14px' }}>
            Print / Save as PDF
          </button>
          <button className="btn-secondary" onClick={handleShareReport} style={{ justifyContent: 'center', fontSize: '14px' }}>
            Share Report
          </button>
        </div>
        <button className="btn-secondary" onClick={handleCopyReport} style={{ justifyContent: 'center', fontSize: '14px' }}>
          Copy Full Report Text
        </button>
        <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '8px', width: '100%' }}>
          <button className="btn-secondary" onClick={onRetry} style={{ justifyContent: 'center' }}>
            <RotateCcw size={15} /> Retry
          </button>
          <button className="btn-secondary" onClick={onBackToDashboard} style={{ justifyContent: 'center' }}>
            History
          </button>
        </div>
      </div>
    </div>
  );
};
export default FeedbackReportView;
