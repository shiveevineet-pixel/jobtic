function normalizeScore(val: unknown, fallback = 70): number {
  let num = typeof val === 'number' ? val : parseFloat(String(val || ''));
  if (isNaN(num)) return fallback;
  if (num <= 10 && num > 0) num = num * 10;
  return Math.min(100, Math.max(0, Math.round(num)));
}

async function executeGroqTextCall(
  apiKey: string,
  systemPrompt: string,
  userPrompt: string,
  temperature = 0.4
): Promise<string> {
  const models = [GROQ_TEXT_MODEL, GROQ_FALLBACK_MODEL];
  let lastError: Error | null = null;

  for (const activeKey of getGroqApiKeys(apiKey)) {
    for (const model of models) {
      try {
        void activeKey;
        const response = await aiProxy('groq', model, {
          model,
          messages: [
            { role: 'system', content: systemPrompt },
            { role: 'user', content: userPrompt }
          ],
          temperature,
          reasoning_effort: 'low',
          max_completion_tokens: 6500,
          response_format: { type: 'json_object' }
        });

      if (!response.ok) {
        const err = await response.text();
        throw new Error(`Groq API error (${model}) ${response.status}: ${err}`);
      }

        const data = await response.json();
        const content = data.choices?.[0]?.message?.content;
        if (!content) throw new Error(`Empty content from Groq model ${model}`);
        return content;
      } catch (err: unknown) {
        lastError = err instanceof Error ? err : new Error(String(err));
        console.warn(`Groq ${model} attempt failed; rotating model/key:`, err);
      }
    }
  }

  throw lastError || new Error('All Groq models failed for resume request.');
}

async function executeGeminiResumeCall(apiKey: string, prompt: string): Promise<string> {
  void apiKey;
  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), AI_REQUEST_TIMEOUT_MS);

  try {
    const response = await aiProxy('gemini', GEMINI_RESUME_MODEL, {
          system_instruction: { parts: [{ text: RESUME_ENHANCEMENT_SYSTEM_PROMPT }] },
          contents: [{ role: 'user', parts: [{ text: prompt }] }],
          generationConfig: {
            responseMimeType: 'application/json',
            temperature: 0.3,
            maxOutputTokens: 6500
          }
    }, controller.signal);

    if (!response.ok) {
      const details = (await response.text()).slice(0, 500);
      throw new Error(`Gemini API error ${response.status}${details ? `: ${details}` : ''}`);
    }

    const payload = await response.json() as {
      candidates?: Array<{ content?: { parts?: Array<{ text?: string }> } }>;
    };
    const content = payload.candidates?.[0]?.content?.parts
      ?.map(part => part.text || '')
      .join('')
      .trim();
    if (!content) throw new Error('Gemini returned an empty resume response.');
    return content;
  } catch (error) {
    if (error instanceof DOMException && error.name === 'AbortError') {
      throw new Error('Gemini resume enhancement timed out.');
    }
    throw error;
  } finally {
    window.clearTimeout(timeout);
  }
}

