// ── Helpers ───────────────────────────────────────────────────────────────────

function cleanJson(value: string): string {
  let text = value.trim();
  text = text.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '').trim();
  const firstBrace = text.indexOf('{');
  const lastBrace = text.lastIndexOf('}');
  if (firstBrace !== -1 && lastBrace > firstBrace) {
    return text.slice(firstBrace, lastBrace + 1);
  }
  return text;
}

function isReadableText(text: string): boolean {
  const t = text.trim();
  if (t.length < 80) return false;
  const binaryHints = ['%PDF-', 'endobj', 'endstream', '%%EOF'];
  if (binaryHints.some(h => t.includes(h))) return false;
  const words = t.match(/[a-zA-Z]{3,}/g);
  return !!words && words.length >= 15;
}

function asText(value: unknown): string {
  return typeof value === 'string' ? value.trim() : '';
}

function asTextArray(value: unknown): string[] {
  return Array.isArray(value) ? value.map(asText).filter(Boolean) : [];
}

function removeBrandingFromName(value: unknown): string {
  const cleaned = asText(value)
    .replace(/\bjobtic(?:\s+ai)?\b/gi, '')
    .replace(/\b(?:ai[ -]?)?enhanced\s+resume\b/gi, '')
    .replace(/\bai[ -]?generated\b/gi, '')
    .replace(/^[\s|:–—-]+|[\s|:–—-]+$/g, '')
    .trim();
  return cleaned || 'Candidate';
}

/**
 * Normalize model output before it reaches the UI/PDF. Besides preventing
 * malformed responses from crashing the view, this is a final enforcement
 * layer that keeps app/AI branding out of the resume heading.
 */
function normalizeEnhancedResume(value: unknown): EnhancedResume {
  const root = value && typeof value === 'object' ? value as Record<string, unknown> : {};
  const rawData = root.data && typeof root.data === 'object'
    ? root.data as Record<string, unknown>
    : {};
  const rawPersonal = rawData.personalInfo && typeof rawData.personalInfo === 'object'
    ? rawData.personalInfo as Record<string, unknown>
    : {};

  const objectArray = (input: unknown): Record<string, unknown>[] =>
    Array.isArray(input)
      ? input.filter((item): item is Record<string, unknown> => !!item && typeof item === 'object')
      : [];

  return {
    data: {
      personalInfo: {
        name: removeBrandingFromName(rawPersonal.name),
        email: asText(rawPersonal.email),
        phone: asText(rawPersonal.phone),
        linkedin: asText(rawPersonal.linkedin),
        location: asText(rawPersonal.location)
      },
      summary: asText(rawData.summary),
      experience: objectArray(rawData.experience).map(item => ({
        title: asText(item.title),
        company: asText(item.company),
        date: asText(item.date),
        location: asText(item.location),
        bullets: asTextArray(item.bullets)
      })),
      education: objectArray(rawData.education).map(item => ({
        degree: asText(item.degree),
        school: asText(item.school),
        date: asText(item.date),
        location: asText(item.location)
      })),
      skills: objectArray(rawData.skills).map(item => ({
        category: asText(item.category),
        items: asTextArray(item.items)
      })).filter(item => item.category || item.items.length > 0),
      projects: objectArray(rawData.projects).map(item => ({
        name: asText(item.name),
        description: asText(item.description),
        technologies: asText(item.technologies),
        date: asText(item.date)
      })),
      certifications: objectArray(rawData.certifications).map(item => ({
        name: asText(item.name),
        issuer: asText(item.issuer),
        date: asText(item.date)
      })),
      awards: asTextArray(rawData.awards),
      languages: asTextArray(rawData.languages),
      additionalSections: objectArray(rawData.additionalSections).map(item => ({
        title: asText(item.title),
        items: asTextArray(item.items)
      })).filter(item => item.title && item.items.length > 0)
    },
    changesSummary: asTextArray(root.changesSummary).slice(0, 7)
  };
}

function enhancedResumeWordCount(resume: EnhancedResume): number {
  const searchable = JSON.stringify(resume.data)
    .replace(/[{}[\]":,]/g, ' ')
    .match(/[a-zA-Z0-9][a-zA-Z0-9+.#/-]*/g);
  return searchable?.length || 0;
}

function isUsableEnhancedResume(resume: EnhancedResume, original: string): boolean {
  const enhancedWords = enhancedResumeWordCount(resume);
  if (enhancedWords < 35) return false;

  const originalHasEmail = /[\w.+-]+@[\w.-]+\.[a-z]{2,}/i.test(original);
  if (originalHasEmail && !resume.data.personalInfo.email) return false;
  const hasResumeContent = Boolean(
    resume.data.summary ||
    resume.data.experience.length ||
    resume.data.education.length ||
    resume.data.projects.length ||
    resume.data.skills.length ||
    resume.data.additionalSections.length
  );
  return resume.data.personalInfo.name !== 'Candidate' && hasResumeContent;
}

/**
 * Render every page of a PDF to a base64 PNG image using PDF.js canvas rendering.
 * This lets the NVIDIA vision model "see" the resume visually, exactly like a human.
 */
async function renderPdfToImages(file: File, maxPages = 4): Promise<string[]> {
  const arrayBuffer = await file.arrayBuffer();
  const pdf = await pdfjsLib.getDocument({ data: new Uint8Array(arrayBuffer) }).promise;
  const pageCount = Math.min(pdf.numPages, maxPages);
  const images: string[] = [];

  for (let i = 1; i <= pageCount; i++) {
    const page = await pdf.getPage(i);
    // Scale to ~1.5× for good readability without hitting token limits
    const viewport = page.getViewport({ scale: 1.5 });

    const canvas = document.createElement('canvas');
    canvas.width = viewport.width;
    canvas.height = viewport.height;
    const ctx = canvas.getContext('2d')!;

    await page.render({ canvasContext: ctx, viewport }).promise;

    // Convert to JPEG at 80% quality to keep image size manageable
    const base64 = canvas.toDataURL('image/jpeg', 0.8).split(',')[1];
    images.push(base64);
  }

  return images;
}

/**
 * Extract plain text from all pages of a PDF (used as fallback + for enhancement).
 */
async function extractPdfText(file: File): Promise<string> {
  const arrayBuffer = await file.arrayBuffer();
  const pdf = await pdfjsLib.getDocument({ data: new Uint8Array(arrayBuffer) }).promise;
  const parts: string[] = [];

  for (let i = 1; i <= pdf.numPages; i++) {
    const page = await pdf.getPage(i);
    const content = await page.getTextContent();
    const pageText = content.items
      .map((item: unknown) => (item && typeof item === 'object' && 'str' in item && typeof (item as { str: unknown }).str === 'string' ? (item as { str: string }).str : ''))
      .join(' ');
    parts.push(pageText);
  }

  return parts.join('\n\n').replace(/\s{3,}/g, ' ').trim();
}

